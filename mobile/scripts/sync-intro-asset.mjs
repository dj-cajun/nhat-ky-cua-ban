#!/usr/bin/env node
/**
 * Generates intro-asset.generated.ts so Metro only `require`s the MP4 when it exists.
 * Drop `assets/intro/universe-birth.mp4` → next start/typecheck picks it up.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mp4 = path.join(root, 'assets/intro/universe-birth.mp4');
const out = path.join(root, 'src/features/universe-home/intro-asset.generated.ts');

const exists = fs.existsSync(mp4);
const body = exists
  ? `/* auto-generated by scripts/sync-intro-asset.mjs — do not edit */
/* eslint-disable @typescript-eslint/no-require-imports */
export const INTRO_VIDEO_SOURCE: number = require('../../../assets/intro/universe-birth.mp4');
export const HAS_INTRO_VIDEO = true as const;
`
  : `/* auto-generated by scripts/sync-intro-asset.mjs — do not edit */
export const INTRO_VIDEO_SOURCE: number | null = null;
export const HAS_INTRO_VIDEO = false as const;
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev !== body) {
  fs.writeFileSync(out, body);
  console.log(`[sync-intro-asset] ${exists ? 'bundled universe-birth.mp4' : 'no mp4 → synthetic intro'}`);
}
